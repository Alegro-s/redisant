def para(*sentences: str) -> str:
    return "\n\n".join(sentences) + "\n\n"


def bullets(items: list[str]) -> str:
    return "\n".join(f"– {x};" for x in items) + "\n\n"


def section(title: str, key: str, *paragraphs: str) -> str:
    out = [f"### {title}\n\n"]
    for p in paragraphs:
        out.append(p + "\n\n")
    for p in EXTRA.get(key, []):
        out.append(p + "\n\n")
    for p in DEEP.get(key, []):
        out.append(p + "\n\n")
    return "".join(out)


