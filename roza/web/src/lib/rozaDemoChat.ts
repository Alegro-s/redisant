export function rozaDemoReply(question: string): string {
  const q = question.toLowerCase();

  if (q.includes('документ') || q.includes('сводк') || q.includes('файл')) {
    return 'Могу помочь со сводкой и структурой документа. В приложении Roza для Windows можно прикреплять файлы и работать с ними локально.';
  }
  if (q.includes('угроз') || q.includes('безопас') || q.includes('вирус') || q.includes('пк')) {
    return 'Для анализа системы и подозрительной активности используйте десктопное приложение Roza: разделы диагностики и отчёты по безопасности ПК.';
  }
  if (q.includes('обучен') || q.includes('курс') || q.includes('урок')) {
    return 'В приложении Roza доступны сценарии обучения и журнал прогресса. Откройте раздел «Студия» после установки консультанта.';
  }
  if (q.includes('api') || q.includes('ключ')) {
    return 'Ключи API и лимиты настраиваются в личном кабинете после подписки.';
  }
  if (q.includes('привет') || q.includes('здрав')) {
    return 'Здравствуйте. Я Roza — консультант по документам, безопасности ПК и обучению. Задайте вопрос или установите приложение для полного доступа.';
  }

  return 'Уточните задачу: документы, безопасность системы, обучение или доступ через API. Полный функционал — в приложении Roza для Windows.';
}

export function rozaTypingDelayMs(): number {
  return 900 + Math.random() * 700;
}
